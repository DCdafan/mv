// 文档截图：打开 smoke 测试生成的项目，截取编辑器各个面板
import { _electron as electron } from 'playwright-core'
import { join, resolve } from 'path'
const ROOT = resolve('.')
const OUT = join(ROOT, 'e2e/shots')
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const app = await electron.launch({ args: [join(ROOT, 'out/main/index.js')], env: { ...process.env, MV_USER_DATA: join(OUT, 'userdata') } })
const page = await app.firstWindow()
await page.waitForSelector('.proj')
await sleep(2500)
await page.screenshot({ path: join(OUT, 'd01-home.png') })
await page.click('.proj')
await page.waitForSelector('.timeline')
await sleep(2000)
await page.screenshot({ path: join(OUT, 'd02-editor.png') })
// 选中第 5 个场景，展示属性面板
const blocks = await page.$$('.timeline [draggable="true"]')
await blocks[3].click()
await sleep(1200)
await page.screenshot({ path: join(OUT, 'd03-scene.png') })
await page.click('.tabs button:has-text("转场")')
await sleep(500)
await page.screenshot({ path: join(OUT, 'd04-transitions.png') })
await page.click('.tabs button:has-text("音乐")')
await sleep(800)
await page.screenshot({ path: join(OUT, 'd05-music.png') })
await page.click('.tabs button:has-text("模板")')
await sleep(3000)
await page.screenshot({ path: join(OUT, 'd06-templates.png') })
await app.close()
